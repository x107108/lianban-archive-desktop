const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const path = require("node:path");
const source = fs.readFileSync(path.join(__dirname, "../web/app.js"), "utf8");
const context = vm.createContext({state:{}});
vm.runInContext(source.slice(source.indexOf("function stockTags("), source.indexOf("function canEditTags(")), context);
vm.runInContext(source.slice(source.indexOf("function defaultEditorTags("), source.indexOf("function updateTagEditorControls(")), context);
const plural = context.defaultEditorTags({source_tag: "旧行业", source_tags: ["机器人", "风电"]});
assert.deepEqual(Array.from(plural), ["机器人", "风电"]);
assert.deepEqual(Array.from(context.defaultEditorTags({source_tag: "旧行业", source_tags: []})), []);
assert.deepEqual(Array.from(context.defaultEditorTags({source_tag: "旧行业"})), ["旧行业"]);
const data = {source_tags: ["机器人", "风电"]};
context.defaultEditorTags(data).push("修改草稿");
assert.deepEqual(data.source_tags, ["机器人", "风电"], "reading defaults does not mutate the loaded source list");
console.log("Plural concept defaults, empty intersection and legacy compatibility: passed.");
